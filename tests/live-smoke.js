// Run using Obsidian's developer CLI eval. All text and archives are isolated
// under this source project's ignored test directory; no vault notes are edited.
(async () => {
  const real = app.plugins.plugins['track-changes'];
  if (!real?.ready) throw Error('Installed plugin is not ready');
  const checked=[];
  const assert=(condition,message)=>{if(!condition)throw Error(message);checked.push(message);};
  if(!globalThis.__trackChangesTestDirectory)throw Error('Set __trackChangesTestDirectory to an absolute tests/.runtime directory first');
  const root = require('path').join(globalThis.__trackChangesTestDirectory,`live-${Date.now()}`);
  const instance = new real.constructor(app,real.manifest);
  instance.archive = new real.archive.constructor(root);
  await instance.archive.init();instance.ready=true;
  instance.refreshEditors=()=>{};instance.refreshViews=()=>{};
  let text='Original paragraph.\nSecond line.';
  const editor={getValue:()=>text,setValue:value=>{text=value;instance.schedule('fixture.md',value);}};
  instance.editorFor=notePath=>notePath==='fixture.md'?editor:undefined;
  await instance.capture('fixture.md',text);
  text='Rewritten paragraph.\nSecond line!';instance.schedule('fixture.md',text);await instance.flushAll();
  const before=text,base=instance.archive.get('fixture.md').baseline;
  assert(base==='Original paragraph.\nSecond line.','Initial baseline preserved after editing');
  await instance.applyChange('fixture.md',text,base,undefined,false);
  assert(text===base,'Reject all restores accepted text');
  let names=await instance.archive.list(instance.archive.get('fixture.md').docId);
  const versions=await Promise.all(names.map(name=>instance.archive.load(instance.archive.get('fixture.md').docId,name)));
  assert(versions.some(r=>r.kind==='before-reject'&&r.content===before),'Rejected text remains recoverable');
  text='Accepted rewrite';instance.schedule('fixture.md',text);
  await instance.applyChange('fixture.md',text,base,undefined,true);
  assert(instance.archive.get('fixture.md').baseline===text,'Accept all persists new baseline');
  const expected=text;text='Changed while reviewing';
  let refused=false;try{await instance.applyChange('fixture.md',expected,expected,undefined,false);}catch{refused=true;}
  assert(refused&&text==='Changed while reviewing','Stale review cannot replace newer editor text');
  instance.schedule('fixture.md',text);await instance.flushAll();
  await instance.replaceSafely('fixture.md',text,'Original paragraph.\nSecond line.','restore');
  assert(text==='Original paragraph.\nSecond line.','Restore writes selected revision');
  names=await instance.archive.list(instance.archive.get('fixture.md').docId);
  const restored=await Promise.all(names.map(name=>instance.archive.load(instance.archive.get('fixture.md').docId,name)));
  assert(restored.some(r=>r.kind==='before-restore'&&r.content==='Changed while reviewing'),'Restore preserves preceding editor text');
  // Recover-as-copy uses a mock vault to verify the actual plugin action safely.
  let created,opened;
  instance.app={vault:{create:async(name,content)=>{created={path:name,content};return created;}},workspace:{getLeaf:()=>({openFile:async file=>{opened=file;}})}};
  await instance.recoverCopy(restored.find(r=>r.content===before));
  assert(created?.content===before&&opened===created&&created.path.includes('(recovered '),'Recover as copy creates and opens an independent note');
  // Exercise the actual installed CodeMirror extension in a disposable editor.
  const active=app.workspace.getLeavesOfType('markdown').find(l=>l.view.editor?.cm)?.view.editor.cm;
  if(!active)throw Error('An open Markdown editor is needed for the inline smoke test');
  const editorInfoField=real.editorContextField;
  const mount=document.createElement('div');mount.style.position='fixed';mount.style.left='-10000px';document.body.appendChild(mount);
  const State=active.state.constructor,View=active.constructor;
  const waitFor=async(predicate,label)=>{const until=Date.now()+5000;while(!predicate()&&Date.now()<until)await new Promise(r=>setTimeout(r,25));assert(!!predicate(),label);};
  let cm;
  try{
    const initial='That is the original introduction.\n\nA second paragraph stays here.\n\nThe final paragraph is unchanged.';
    const edited='That is the revised introduction.\n\nA second paragraph now has a change.\n\nThe final paragraph has a new ending.';
    await instance.capture('inline-fixture.md',initial);
    const state=State.create({doc:initial,extensions:[editorInfoField.init(()=>({file:{path:'inline-fixture.md'}})),instance.extension()]});
    cm=new View({state,parent:mount});
    const fixtureEditor=instance.editorFor;
    instance.editorFor=notePath=>notePath==='inline-fixture.md'?{getValue:()=>cm.state.doc.toString(),setValue:value=>cm.dispatch({changes:{from:0,to:cm.state.doc.length,insert:value}})}:fixtureEditor(notePath);
    cm.dispatch({changes:{from:0,to:cm.state.doc.length,insert:edited}});
    assert(!!mount.querySelector('.tc-addition'),'Inline addition decoration renders');
    assert([...mount.querySelectorAll('.tc-deletion')].some(el=>el.textContent.length>0),'Inline deletion decoration renders');
    assert(Array.from(mount.querySelectorAll('.tc-deletion')).some(el=>el.textContent==='original'),'Deleted words stay whole instead of interleaving character fragments');
    const cards=()=>Array.from(mount.querySelectorAll('.tc-inline-review'));
    const marker=index=>mount.querySelector(`.tc-addition[data-tc-area="${index}"],.tc-deletion[data-tc-area="${index}"]`);
    const hover=index=>marker(index).dispatchEvent(new PointerEvent('pointerover',{bubbles:true}));
    const action=(index,name)=>{hover(index);cards()[0].querySelector(`[data-action="${name}"]`).click();};
    assert(cards().length===0&&!mount.querySelector('.tc-inline-container'),'Review boxes are hidden at rest without reserving document space');
    cm.dispatch({selection:{anchor:edited.indexOf('revised')}});
    assert(cards().length===0,'Putting the cursor in changed text does not reveal a box');
    hover(0);assert(cards().length===1&&cards()[0].dataset.changeIndex==='0','Hovering changed text reveals only that area\'s box');
    const sourceMarker=marker(0),hoveredCard=cards()[0];
    sourceMarker.dispatchEvent(new PointerEvent('pointerout',{bubbles:true,relatedTarget:hoveredCard}));
    hoveredCard.dispatchEvent(new PointerEvent('pointerover',{bubbles:true,relatedTarget:sourceMarker}));
    await new Promise(r=>setTimeout(r,300));
    assert(cards()[0]===hoveredCard,'The review box stays open while moving from changed text onto its controls');
    cm.dom.dispatchEvent(new PointerEvent('pointerover',{bubbles:true}));
    await waitFor(()=>cards().length===0,'The review box closes after moving away from both text and controls');
    hover(0);
    assert(cards()[0].querySelector('[data-action="previous"]').disabled,'Previous is disabled at the first changed area');
    hover(2);assert(cards().length===1&&cards()[0].dataset.changeIndex==='2','Hovering another change replaces the currently open box');
    assert(cards()[0].querySelector('[data-action="next"]').disabled,'Next is disabled at the final changed area');
    action(0,'next');
    assert(cm.state.selection.main.head===edited.indexOf('now')&&cards()[0].dataset.changeIndex==='1','Next change moves to the following area and reveals its controls');
    action(1,'previous');
    assert(cm.state.selection.main.head===Number(cards()[0].dataset.from)&&cards()[0].dataset.changeIndex==='0','Previous change moves back and reveals the preceding controls');
    instance.settings.highlights=false;cm.dispatch({});assert(cards().length===0,'Disabling highlights hides review boxes');
    instance.settings.highlights=true;cm.dispatch({});assert(cards().length===0&&!!marker(0),'Re-enabling highlights keeps boxes hidden until hover');
    action(0,'accept');
    await waitFor(()=>cards().length===0&&instance.archive.get('inline-fixture.md').baseline!==initial,'Accept closes the resolved area\'s hover box');
    assert(instance.archive.get('inline-fixture.md').baseline==='That is the revised introduction.\n\nA second paragraph stays here.\n\nThe final paragraph is unchanged.','Accept keeps the other paragraphs pending');
    assert(cm.state.doc.toString()===edited,'Accept does not rewrite the note text');
    action(0,'reject');
    await waitFor(()=>cards().length===0&&cm.state.doc.toString()!==edited,'Reject closes the resolved area\'s hover box');
    assert(cm.state.doc.toString()==='That is the revised introduction.\n\nA second paragraph stays here.\n\nThe final paragraph has a new ending.','Reject restores its paragraph without changing the others');
    const inlineDoc=instance.archive.get('inline-fixture.md');
    const inlineRevisions=await Promise.all((await instance.archive.list(inlineDoc.docId)).map(name=>instance.archive.load(inlineDoc.docId,name)));
    assert(inlineRevisions.some(r=>r.kind==='before-reject'&&r.content===edited),'Inline rejection preserves the replaced text in revision history');
    action(0,'reject');await waitFor(()=>cards().length===0,'Resolving the final change removes the final box');
    assert(!mount.querySelector('.tc-addition')&&!mount.querySelector('.tc-deletion'),'Resolved text has no residual change decorations');
    const acceptedText=cm.state.doc.toString();
    cm.dispatch({changes:{from:0,to:cm.state.doc.length,insert:''}});
    assert(cards().length===0&&cm.state.doc.length===0,'A complete deletion does not leave an always-visible review box');
    hover(0);assert(cards().length===1,'Hovering deleted text opens controls even when the note is empty');
    action(0,'reject');await waitFor(()=>cards().length===0&&cm.state.doc.toString()===acceptedText,'Rejecting a complete deletion restores all accepted text');
    cm.dispatch({changes:{from:cm.state.doc.length,insert:'\n\nA newly inserted paragraph.'}});
    hover(0);
    assert(cards().length===1&&cards()[0].querySelector('.tc-inline-title').textContent==='Added text','A pure insertion receives its own review box');
    const detachedAccept=cards()[0].querySelector('[data-action="accept"]');
    cm.dispatch({changes:{from:cm.state.doc.length,insert:' More detail.'}});
    const latestText=cm.state.doc.toString();detachedAccept.click();await new Promise(r=>setTimeout(r,30));
    assert(instance.archive.get('inline-fixture.md').baseline===acceptedText&&cm.state.doc.toString()===latestText,'A stale detached review button cannot accept or rewrite newer text');
    action(0,'accept');await waitFor(()=>cards().length===0,'Accepting an inserted paragraph resolves its review box');
    await instance.flushAll();
  } finally {cm?.destroy();mount.remove();}
  await instance.archive.idle();
  instance.schedule('shutdown-fixture.md','Pending text at unload');
  instance.onunload();
  const handoff=globalThis[Symbol.for('obsidian-track-changes.archive-handoffs')]?.get(root);
  assert(handoff instanceof Promise,'Reload handoff exposes the final flush promise');
  await handoff;
  const restarted=new real.archive.constructor(root);await restarted.init();
  assert(restarted.get('shutdown-fixture.md')?.content==='Pending text at unload','Reload handoff preserves pending text before the next scan');
  const result={passed:checked.length,checks:checked,isolatedArchive:root,installedReady:real.ready};
  await require('fs').promises.writeFile(require('path').join(root,'result.json'),JSON.stringify(result,null,2));
  return result;
})()
